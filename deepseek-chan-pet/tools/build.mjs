// Builds lib/client.js (the DSH browser module) and preview/index.html (offline demo).
// No dependencies: plain Node >= 22.  Usage: node tools/build.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { EMOTIONS } from '../src/dialogue.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
const pkg = JSON.parse(read('package.json'));
const KNOWN_POSES = new Set(Object.values(EMOTIONS).map(e => e.pose));
const MIME = { '.webp': 'image/webp', '.png': 'image/png', '.gif': 'image/gif', '.apng': 'image/apng', '.webm': 'video/webm', '.mp4': 'video/mp4' };
const BUDGET_BYTES = 8 * 1024 * 1024;   // everything is inlined into one JS file

function dataUri(file) {
  const bytes = fs.readFileSync(file);
  return `data:${MIME[path.extname(file).toLowerCase()]};base64,${bytes.toString('base64')}`;
}
function scan(dir, extensions) {
  const full = path.join(root, dir);
  if (!fs.existsSync(full)) return [];
  return fs.readdirSync(full)
    .filter(name => extensions.includes(path.extname(name).toLowerCase()))
    .sort()
    .map(name => ({ pose: path.basename(name, path.extname(name)), file: path.join(full, name), name }));
}
function checkPose(pose, where) {
  if (!KNOWN_POSES.has(pose)) console.warn(`  ! ${where}/${pose}: no emotion uses pose "${pose}" (known: ${[...KNOWN_POSES].join(', ')})`);
}

// 1) Sprites (required) — cut from the source art by tools/process-art.py.
const sprites = {};
for (const { pose, file } of scan('assets/sprites', ['.webp', '.png'])) sprites[pose] = dataUri(file);
for (const pose of KNOWN_POSES) if (!sprites[pose]) throw new Error(`Missing sprite for pose "${pose}" in assets/sprites/`);

// 2) Optional animated images replace a sprite (keeps the <img> path: transparent, no decoder).
for (const { pose, file, name } of scan('assets/animated', ['.webp', '.gif', '.png', '.apng'])) {
  checkPose(pose, 'assets/animated'); sprites[pose] = dataUri(file); console.log(`  animated image: ${name}`);
}

// 3) Optional videos replace a sprite with a looping, muted <video>.
const videos = {};
for (const { pose, file, name } of scan('assets/videos', ['.webm', '.mp4'])) {
  checkPose(pose, 'assets/videos');
  if (videos[pose]) { console.warn(`  ! assets/videos/${name}: ${pose} already has a video, keeping the first one`); continue; }
  videos[pose] = dataUri(file); console.log(`  video: ${name}`);
}

const media = { sprites, videos };
const mediaJson = JSON.stringify(media);
if (mediaJson.length > BUDGET_BYTES) {
  console.warn(`  ! embedded media is ${(mediaJson.length / 1048576).toFixed(1)} MB; keep it under ${BUDGET_BYTES / 1048576} MB so DSH loads quickly`);
}

// Concatenate the ES modules into one factory body: drop imports, keep declarations.
const strip = file => read(file).replace(/^import [^\n]*\n/gm, '').replace(/^export /gm, '');
const css = read('src/pet.css');
const common = ['src/dialogue.js', 'src/i18n.js', 'src/state.js', 'src/widget.js'].map(strip).join('\n');
const header = `const MEDIA=${mediaJson};\nconst CSS=${JSON.stringify(css)};\n`;

fs.mkdirSync(path.join(root, 'lib'), { recursive: true });
fs.writeFileSync(path.join(root, 'lib/client.js'),
  `// Generated by tools/build.mjs from src/. Do not edit by hand.\n` +
  `window.__ModuleLoader__.load({id:${JSON.stringify(pkg.name)},factory:function(require){\n'use strict';\n` +
  `${header}${common}\n${strip('src/adapter.js')}\nreturn createPlugin(require, MEDIA, CSS);\n}});\n`);

fs.mkdirSync(path.join(root, 'preview'), { recursive: true });
const runtime = `(function(){'use strict';\n${header}${common}\n` +
  `window.DeepSeekChan={PetWidget,SessionTracker,PetBrain,LINES,EMOTIONS,MEDIA,CSS};\n})();\n`;
const html = read('src/preview.html')
  .replaceAll('__VERSION__', pkg.version)
  .replace('/*__RUNTIME__*/', () => runtime.replace(/<\/script/gi, '<\\/script'));
fs.writeFileSync(path.join(root, 'preview/index.html'), html);

const kb = file => Math.round(fs.statSync(path.join(root, file)).size / 1024);
console.log(`Built lib/client.js (${kb('lib/client.js')} KB, ${Object.keys(sprites).length} poses, ${Object.keys(videos).length} videos) and preview/index.html.`);
